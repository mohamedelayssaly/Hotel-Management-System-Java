    private void gradientButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_gradientButton2ActionPerformed
      
        
if(!duree.getText().equals("")){
    try {
        Connection con=DbConnection.getInstance().getConnection();
        Statement stmt=con.createStatement();
        String sql3="SELECT solde FROM  conge  WHERE matricule="+GestionConge.matricdemande;
        ResultSet res= stmt.executeQuery(sql3);
        while(res.next()){
            if(res.getInt("solde")>=Integer.parseInt(duree.getText())) {
                    LocalDate date1 = LocalDate.parse(datesorti.getText());
            LocalDate date2 = LocalDate.parse(dateentrer.getText());

            int comparison = date1.compareTo(date2);
  long daysBetween = ChronoUnit.DAYS.between(date1, date2);
      
            if (comparison < 0) {
               if(daysBetween==Integer.parseInt(duree.getText())){
                 DataBase.CongeDao.addConge(GestionConge.matricdemande, datesorti.getText(), dateentrer.getText(), Integer.parseInt(duree.getText()));
                
                JOptionPane.showMessageDialog(this, "commande reussit");
                Sorticonge.super.dispose();
                Sorticonge sor=new Sorticonge();
                sor.setVisible(true);
               }else{
               JOptionPane.showMessageDialog(this, "Erreur la duree est incorrect");    
               }
            } else if (comparison > 0) {
JOptionPane.showMessageDialog(this, "la date d'entrer doit etre superieur de date sertie");
            } 
                
               
            }else{
                JOptionPane.showMessageDialog(this, "la duree est superieur de solde ");
            }
        }
    } catch (SQLException ex) {
        Logger.getLogger(Sorticonge.class.getName()).log(Level.SEVERE, null, ex);
    }
}else{
    JOptionPane.showMessageDialog(this, "entrer la duree");
}
        
        
        
        
        
        
        
        
        
        
    }//GEN-LAST:event_gradientButton2ActionPerformed

