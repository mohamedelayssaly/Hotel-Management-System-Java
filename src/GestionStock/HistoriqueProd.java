            Connection con=DbConnection.getInstance().getConnection();
            Statement stmt=con.createStatement();
            
            String sql="SELECT * FROM product WHERE ref="+ListProduit.selectedref;
            ResultSet res=stmt.executeQuery(sql);
            while(res.next()){
                
                ref.setText(res.getInt("ref")+"");
                discri.setText(res.getString("discription"));
                prix.setText(res.getFloat("prix")+"");
}
              String sql1="SELECT * FROM prodhesto WHERE refprod="+ListProduit.selectedref;
            ResultSet res1=stmt.executeQuery(sql1);
            while(res1.next()){
                model.addRow(new  Object[]{
                  res1.getDate("date"),
                    res1.getInt("qte"),
                    res1.getString("action")
                });
                
}        
            
