    private void gradientButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_gradientButton2ActionPerformed
     
if(!matricule.getText().equals("") && !nom.getText().equals("") && !prenom.getText().equals("")
        &&  !cin.getText().equals("") && !poste.getText().equals("") && !dateemb.getText().equals("") && !heure.getText().equals("")
        && !salaire.getText().equals("") && !tele.getText().equals("") ){
    

        
     boolean inser=DataBase.EmployeDao.insertEmp(Integer.parseInt(matricule.getText()),nom.getText(),prenom.getText(),
             cin.getText(),poste.getText(),dateemb.getText(),Integer.parseInt(heure.getText()),
             Integer.parseInt( salaire.getText()),Integer.parseInt(tele.getText()));
    
      if (inser){
          JOptionPane.showMessageDialog(this, "Employee ajouter avec succe");
      AddEmploye.super.dispose();
      AddEmploye ad=new AddEmploye();
      ad.setVisible(true);
      
      } else{
            JOptionPane.showMessageDialog(this, "erreur d'ajouter l'employee");
       
      }    
        
      }else{
    JOptionPane.showMessageDialog(this, "Inserer tout les champs");
}  
        
        
        
    }//GEN-LAST:event_gradientButton2ActionPerformed

