    private void gradientButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_gradientButton2ActionPerformed
     
        String type="";
        boolean selecttype=false;
        if(materiele.isSelected()){
          type="materièle";  
          selecttype=true;
        }
         if(restaurant.isSelected()){
          type="restaurant";  
          selecttype=true;
        }
        if(!ref.getText().equals("") && !discription.getText().equals("") && !qte.getText().equals("") && 
                !prix.getText().equals("") && !type.equals("") ){
            
            
            
            DataBase.ProductDao.addproduct(Integer.parseInt(ref.getText()), discription.getText()
                    , Integer.parseInt(qte.getText()),Float.parseFloat(prix.getText()), type);
            JOptionPane.showMessageDialog(this, "produit ajouter avec succès");
            AddProduct.super.dispose();
            AddProduct d1=new AddProduct();
            d1.setVisible(true);
        }else{
          JOptionPane.showMessageDialog(this, "Insérer tout les champs");  
        }
        
        
        
        
        
    }//GEN-LAST:event_gradientButton2ActionPerformed

