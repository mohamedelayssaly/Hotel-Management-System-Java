public static String cinmdp;
    private void gradientButton10ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_gradientButton10ActionPerformed
      
        
        
        cinmdp=cin.getText();
        try {
            Connection con=DbConnection.getInstance().getConnection();
            Statement stmt=con.createStatement();
            
            String sql="SELECT cin ,password ,droit FROM user";
            ResultSet res=stmt.executeQuery(sql);
            while(res.next()){
              if(res.getString("cin").equals(cin.getText()) && res.getString("password").equals(password.getText()) ){  
        if(res.getString("droit").equals("Manager")){
             exist1=true;
             btnacc=true;
             Login.super.dispose();
            DashboardGeneral d4=new DashboardGeneral();
            d4.setVisible(true);
            
          break;  
        }
          if(res.getString("droit").equals("RH")){
              exist1=true;
              btnacc=false;
              Employees emp=new Employees();
              emp.setVisible(true);
            Login.super.dispose();
             break; 
        }
            if(res.getString("droit").equals("Serveur")){
                 exist1=true;
                 btnacc=false;
            Restaurant_service r1=new Restaurant_service();
            r1.setVisible(true);
            Login.super.dispose();
             break; 
        }
              if(res.getString("droit").equals("Reception")){
                   exist1=true;
                   btnacc=false;
                  Hotel h1=new Hotel();
                  h1.setVisible(true);
            Login.super.dispose();
             break; 
        }
             break; 
            }
            }
            if(exist1==false){
                  JOptionPane.showMessageDialog(this, "  CIN ou Mot de passe Incorrect");
                    }
        } catch (SQLException ex) {
            Logger.getLogger(Login.class.getName()).log(Level.SEVERE, null, ex);
        }
        
        



        
        
        
        
        
    }//GEN-LAST:event_gradientButton10ActionPerformed

